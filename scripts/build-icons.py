#!/usr/bin/env python3
"""
Draws the app icons: a vermilion seal with the character 拼 (pīn, as in 拼音).

  public/pwa-192.png, public/pwa-512.png     home-screen icons
  public/pwa-maskable-512.png                full-bleed version for Android's icon masks
  public/apple-touch-icon.png                180 px, opaque, for iOS
  public/favicon.png                         browser tab

With --android, the source images for the Android launcher icon and splash screen
instead (docs/ANDROID.md, "Launcher icon and splash"):

  assets/icon-only.png         1024 px legacy icon (Android 7 and earlier)
  assets/icon-foreground.png   1024 px adaptive-icon foreground: the glyph in paper colour,
                               inside the central safe zone, on transparency
  assets/icon-background.png   1024 px adaptive-icon background: vermilion
  assets/splash.png            2732 px launch screen, paper
  assets/splash-dark.png       2732 px launch screen, dark paper
  android/app/src/main/res/drawable/ic_launcher_monochrome.xml
                               themed-icon layer (Android 13+): the glyph as a vector,
                               which @capacitor/assets does not generate

`npm run android:assets` runs this, then @capacitor/assets, then adds the monochrome layer.

Needs Pillow, fontTools and the Source Han Serif font that build-fonts.py downloads.
Run: python3 scripts/build-icons.py [--android]
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / ".cache" / "fonts" / "source-han-serif" / "SourceHanSerifCN-SemiBold.otf"
OUT = ROOT / "public"
VERMILION = (176, 55, 42, 255)
PAPER = (247, 244, 238, 255)
DARK_PAPER = (23, 22, 20, 255)
GLYPH = "拼"
ASSETS = ROOT / "assets"
MONOCHROME = ROOT / "android" / "app" / "src" / "main" / "res" / "drawable" / "ic_launcher_monochrome.xml"
# Adaptive icons are 108 dp with a 66 dp safe zone; the glyph's box takes 40% of the canvas (43 dp).
ADAPTIVE_GLYPH = 0.40
# @capacitor/assets insets the foreground image by 16.7% on each side, so the image covers the
# central 72 dp; the same 43 dp glyph is 60% of the image.
FOREGROUND_GLYPH = ADAPTIVE_GLYPH * 108 / 72


def draw(size: int, radius_ratio: float, glyph_ratio: float, background=None) -> Image.Image:
    scale = 4  # draw large and downsample for clean edges
    s = size * scale
    img = Image.new("RGBA", (s, s), background or (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle((0, 0, s - 1, s - 1), radius=int(s * radius_ratio), fill=VERMILION)
    font = ImageFont.truetype(str(FONT), int(s * glyph_ratio))
    left, top, right, bottom = d.textbbox((0, 0), GLYPH, font=font)
    x = (s - (right - left)) / 2 - left
    y = (s - (bottom - top)) / 2 - top
    d.text((x, y), GLYPH, font=font, fill=PAPER)
    return img.resize((size, size), Image.LANCZOS)


def glyph_layer(size: int, box_ratio: float, colour) -> Image.Image:
    """The glyph alone, its bounding box box_ratio of the canvas, centred, on transparency."""
    scale = 4
    s = size * scale
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    probe = ImageFont.truetype(str(FONT), 1000)
    l, t, r, b = d.textbbox((0, 0), GLYPH, font=probe)
    font = ImageFont.truetype(str(FONT), int(1000 * s * box_ratio / max(r - l, b - t)))
    l, t, r, b = d.textbbox((0, 0), GLYPH, font=font)
    d.text(((s - (r - l)) / 2 - l, (s - (b - t)) / 2 - t), GLYPH, font=font, fill=colour)
    return img.resize((size, size), Image.LANCZOS)


def splash(background) -> Image.Image:
    size = 2732
    img = Image.new("RGBA", (size, size), background)
    seal = draw(560, 0.19, 0.66)
    img.alpha_composite(seal, ((size - 560) // 2, (size - 560) // 2))
    return img.convert("RGB")


def monochrome_vector() -> str:
    """The glyph outline as an Android vector drawable on the 108 dp adaptive-icon canvas."""
    from fontTools.ttLib import TTFont
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    from fontTools.pens.boundsPen import BoundsPen

    font = TTFont(str(FONT))
    name = font.getBestCmap()[ord(GLYPH)]
    glyphs = font.getGlyphSet()
    bounds = BoundsPen(glyphs)
    glyphs[name].draw(bounds)
    x0, y0, x1, y1 = bounds.bounds
    k = 108 * ADAPTIVE_GLYPH / max(x1 - x0, y1 - y0)
    # Font units are y-up; the vector canvas is y-down. Centre the box on (54, 54).
    dx = 54 - k * (x0 + x1) / 2
    dy = 54 + k * (y0 + y1) / 2
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    glyphs[name].draw(TransformPen(pen, (k, 0, 0, -k, dx, dy)))
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Themed-icon layer (Android 13+): 拼 from Source Han Serif SemiBold. Generated by npm run android:assets (scripts/build-icons.py). -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        f'    <path android:fillColor="#FFFFFFFF" android:pathData="{pen.getCommands()}" />\n'
        "</vector>\n"
    )


def android() -> None:
    ASSETS.mkdir(exist_ok=True)
    draw(1024, 0.19, 0.66).save(ASSETS / "icon-only.png")
    glyph_layer(1024, FOREGROUND_GLYPH, PAPER).save(ASSETS / "icon-foreground.png")
    Image.new("RGBA", (1024, 1024), VERMILION).save(ASSETS / "icon-background.png")
    splash(PAPER).save(ASSETS / "splash.png")
    splash(DARK_PAPER).save(ASSETS / "splash-dark.png")
    MONOCHROME.parent.mkdir(parents=True, exist_ok=True)
    MONOCHROME.write_text(monochrome_vector(), encoding="utf-8")
    print("Wrote Android icon and splash sources to", ASSETS, "and", MONOCHROME.relative_to(ROOT))


def main() -> None:
    if not FONT.exists():
        raise SystemExit(f"Font not found: {FONT}\nDownload it from https://github.com/adobe-fonts/source-han-serif (SubsetOTF/CN).")
    if "--android" in sys.argv:
        android()
        return
    OUT.mkdir(exist_ok=True)
    draw(192, 0.19, 0.66).save(OUT / "pwa-192.png")
    draw(512, 0.19, 0.66).save(OUT / "pwa-512.png")
    # Maskable: no rounded corners, glyph inside the central 80% safe zone.
    draw(512, 0.0, 0.52).save(OUT / "pwa-maskable-512.png")
    # iOS rounds the corners itself and wants no transparency.
    draw(180, 0.0, 0.62, background=VERMILION).convert("RGB").save(OUT / "apple-touch-icon.png")
    draw(64, 0.19, 0.7).save(OUT / "favicon.png")
    print("Wrote icons to", OUT)


if __name__ == "__main__":
    main()
